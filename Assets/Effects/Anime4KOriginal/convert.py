"""Translate the two pinned upstream CNNs to WGSL. Python 3.10+, no dependencies."""

import argparse
import hashlib
from pathlib import Path
import re
import sys
import zipfile

ROOT = Path(__file__).resolve().parent
ARCHIVE_SHA256 = "139cd282086457c5adc79caf7b75b8b825091d71c9b54958c18745fea62d7ed7"
MODELS = {
    "restore": (
        "Anime4K_Restore_CNN_S.glsl",
        "97c24dc370ab300c108bfaa09db7f175aeff343674842c299cf3940a3d330427",
    ),
    "upscale": (
        "Anime4K_Upscale_CNN_x2_S.glsl",
        "4c53ec2e287908f7ee7bcb266b0170421626d663576468b7d7dafc62962649a4",
    ),
}
OFFSETS = [(x, y) for x in range(-1, 2) for y in range(-1, 2)]
TERM = re.compile(
    r"(?:vec4 result = |result \+= )mat4\(([^)]+)\) \* go_([01])\((-?\d)\.0, (-?\d)\.0\);"
)
BIAS = re.compile(r"result \+= vec4\(([^)]+)\);")


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def translate_layer(name, glsl, first, restore_final):
    terms = TERM.findall(glsl)
    expected = [(sign, x, y) for sign in range(1 if first else 2) for x, y in OFFSETS]
    assert [(int(sign), int(x), int(y)) for _, sign, x, y in terms] == expected
    assert ("max((" not in glsl) == first
    assert ("return result + MAIN_tex(MAIN_pos);" in glsl) == restore_final
    if not restore_final:
        assert "return result;" in glsl
    bias = BIAS.findall(glsl)
    assert len(bias) == 1
    cols = ("lo", "p", "hi")
    result = [
        f"fn {name}(p: vec2<i32>) -> vec4<f32> {{",
        "    let lo = max(p - vec2<i32>(1), vec2<i32>(0));",
        "    let hi = min(p + vec2<i32>(1), vec2<i32>(textureDimensions(source)) - vec2<i32>(1));",
    ]
    for index, (x, y) in enumerate(OFFSETS):
        result.append(
            f"    let tap{index} = textureLoad(source, vec2<i32>({cols[x + 1]}.x, {cols[y + 1]}.y), 0);"
        )
    for index, (values, sign, _, _) in enumerate(terms):
        components = values.split(", ")
        assert len(components) == 16
        # GLSL mat4 and WGSL mat4x4 both take columns in constructor order.
        columns = [", ".join(components[i:i + 4]) for i in range(0, 16, 4)]
        tap = f"tap{index % 9}"
        if not first:
            tap = f"max({'-' if sign == '1' else ''}{tap}, vec4<f32>(0.0))"
        assign = "var sum =" if index == 0 else "sum +="
        result.append(f"    {assign} mat4x4<f32>(")
        result.extend(f"        vec4<f32>({column})," for column in columns)
        result.append(f"    ) * {tap};")
    result.extend([f"    return sum + vec4<f32>({bias[0]});", "}", ""])
    if not restore_final:
        result.extend([
            "@compute @workgroup_size(8, 8)",
            f"fn {name}_features(@builtin(global_invocation_id) id: vec3<u32>) {{",
            "    if all(id.xy < textureDimensions(source)) {",
            "        let p = vec2<i32>(id.xy);",
            f"        textureStore(output_float, p, {name}(p));",
            "    }",
            "}",
            "",
        ])
    return "\n".join(result)


def generate(release):
    parts = ["// Generated by convert.py from bloc97 Anime4K v4.0.1; see LICENSE.\n"]
    for model, (filename, expected_hash) in MODELS.items():
        data = (ROOT / filename).read_bytes()
        if sha256(data) != expected_hash:
            sys.exit(f"Unexpected source checksum: {filename}")
        if release is not None and data != release.read(filename):
            sys.exit(f"Vendored source differs from release: {filename}")
        blocks = data.decode("ascii").split("//!DESC ")[1:]
        assert len(blocks) == (4 if model == "restore" else 5)
        previous = "MAIN"
        for index, glsl in enumerate(blocks[:4]):
            restore_final = model == "restore" and index == 3
            binds = ["MAIN", previous] if restore_final else [previous]
            assert re.findall(r"^//!BIND (\S+)", glsl, re.M) == binds
            assert f"//!WIDTH {previous}.w\n//!HEIGHT {previous}.h\n" in glsl
            save = re.search(r"^//!SAVE (\S+)", glsl, re.M)
            assert save is not None
            previous = save[1]
            parts.append("// " + glsl.splitlines()[0])
            parts.append(translate_layer(f"{model}_{index}", glsl, index == 0, restore_final))
    return "\n".join(parts).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare with the checked-in WGSL")
    parser.add_argument("--release", type=Path, help="verify upstream ZIP and exact member bytes")
    args = parser.parse_args()
    if args.release:
        if sha256(args.release.read_bytes()) != ARCHIVE_SHA256:
            sys.exit("Unexpected release ZIP checksum")
        with zipfile.ZipFile(args.release) as release:
            wgsl = generate(release)
    else:
        wgsl = generate(None)
    if args.check:
        if wgsl != (ROOT / "cnn.wgsl").read_bytes():
            sys.exit("cnn.wgsl is out of date")
    else:
        sys.stdout.buffer.write(wgsl)


if __name__ == "__main__":
    main()
